// Load reads the config at path on top of the defaults. A missing file is not
// an error: the defaults are returned.
func Load(path string) (Config, error) {
	c := Default()
	data, e := os.ReadFile(path)
	if errors.Is(e, fs.ErrNotExist) {
		return c, nil
	}
	if e != nil {
		return c, e
	}
	if e = json.Unmarshal(data, &c); e != nil {
		return c, fmt.Errorf("parse %s: %w", path, e)
	}
	return c, c.Validate()
}

func (c Config) Validate() error {
	for name, v := range map[string]string{
		"interfaces.ethernet":   c.Interfaces.Ethernet,
		"interfaces.bridge":     c.Interfaces.Bridge,
		"wireguard.interface":   c.WireGuard.Interface,
		"modem.address":         c.Modem.Address,
		"display.spi_port":      c.Display.SPIPort,
		"display.reset_pin":     c.Display.ResetPin,
		"display.dc_pin":        c.Display.DCPin,
		"display.cs_pin":        c.Display.CSPin,
		"display.backlight_pin": c.Display.BacklightPin,
	} {
		if v == "" {
			return fmt.Errorf("%s must not be empty", name)
		}
	}
	// Tables 253-255 are the kernel's default, main and local tables.
	if c.WireGuard.Table <= 0 || c.WireGuard.Table >= 253 {
		return fmt.Errorf("wireguard.table must be between 1 and 252")
	}
	if c.WireGuard.RulePriority <= 0 || c.WireGuard.RulePriority >= 32766 {
		return fmt.Errorf("wireguard.rule_priority must be between 1 and 32765")
	}
	if c.Panel.Enabled {
		if _, e := c.PanelPort(); e != nil {
			return e
		}
	}
	if !filepath.IsAbs(c.Network.NetplanFile) || !strings.HasSuffix(c.Network.NetplanFile, ".yaml") {
		return fmt.Errorf("network.netplan_file must be an absolute path ending in .yaml")
	}
	if ip, _, e := net.ParseCIDR(c.Network.BridgeAddress); e != nil || ip.To4() == nil {
		return fmt.Errorf("network.bridge_address must be an IPv4 address in CIDR notation, such as 172.16.0.1/12")
	}
	for _, d := range c.Network.DNS {
		if net.ParseIP(d) == nil {
			return fmt.Errorf("network.dns: %q is not an IP address", d)
		}
	}
	if net.ParseIP(c.WireGuard.HealthTarget) == nil {
		return fmt.Errorf("wireguard.health_target must be an IP address")
	}
	if e := c.validateLAN(); e != nil {
		return e
	}
	if u, e := url.Parse(c.MiniNetMan.URL); e != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
		return fmt.Errorf("mini_net_man.url must be an http or https URL")
	}
	if c.MiniNetMan.Dir != "" && !filepath.IsAbs(c.MiniNetMan.Dir) {
		return fmt.Errorf("mini_net_man.dir must be an absolute path")
	}
	// Names end up in the netplan file; keep them to what interface names use.
	for name, v := range map[string]string{
		"interfaces.ethernet":  c.Interfaces.Ethernet,
		"interfaces.usb_modem": c.Interfaces.USBModem,
		"interfaces.bridge":    c.Interfaces.Bridge,
	} {
		if !validInterfaceName(v) {
			return fmt.Errorf("%s: %q is not a valid interface name", name, v)
		}
	}
	return nil
}

// validateLAN checks the DHCP range against the bridge subnet and the Wi-Fi
// settings, which end up in the hostapd and dnsmasq files.
func (c Config) validateLAN() error {
	_, subnet, _ := net.ParseCIDR(c.Network.BridgeAddress)
	for name, v := range map[string]string{"network.dhcp_start": c.Network.DHCPStart, "network.dhcp_end": c.Network.DHCPEnd} {
		ip := net.ParseIP(v)
		if ip == nil || ip.To4() == nil || !subnet.Contains(ip) {
			return fmt.Errorf("%s must be an IPv4 address inside %s", name, subnet)
		}
	}
	if bytes.Compare(net.ParseIP(c.Network.DHCPStart).To4(), net.ParseIP(c.Network.DHCPEnd).To4()) > 0 {
		return fmt.Errorf("network.dhcp_start must not be after network.dhcp_end")
	}
	return c.WiFi.Validate()
}

// Validate checks the values that end up in hostapd.conf. An empty passphrase
// is allowed: the access point is simply not configured yet.
func (w WiFi) Validate() error {
	if n := len(w.SSID); n < 1 || n > 32 || !printable(w.SSID) {
		return fmt.Errorf("wifi.ssid must be 1 to 32 printable characters")
	}
	if w.Passphrase != "" && (len(w.Passphrase) < 8 || len(w.Passphrase) > 63 || !printable(w.Passphrase)) {
		return fmt.Errorf("wifi.passphrase must be 8 to 63 printable characters")
	}
	if w.Channel < 1 || w.Channel > 165 {
		return fmt.Errorf("wifi.channel must be between 1 and 165")
	}
	return nil
}

func printable(s string) bool {
	for _, r := range s {
		if r < 0x20 || r > 0x7e {
			return false
		}
	}
	return true
}

// validInterfaceName reports whether s is a Linux interface name (at most 15
// characters, no spaces, slashes or colons). An empty name is allowed.
func validInterfaceName(s string) bool {
	if len(s) > 15 {
		return false
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.') {
			return false
		}
	}
	return true
}

// Save writes the config to path, replacing the file atomically. The file
// holds secrets, so it is readable by its owner only.
func (c Config) Save(path string) error {
	data, e := json.MarshalIndent(c, "", "  ")
	if e != nil {
		return e
	}
	if e = os.MkdirAll(filepath.Dir(path), 0o755); e != nil {
		return e
	}
	tmp := path + ".tmp"
	if e = os.WriteFile(tmp, append(data, '\n'), 0o600); e != nil {
		return e
	}
	return os.Rename(tmp, path)
}

// MiniNetManPort returns the TCP port of MiniNetMan.URL.
func (c Config) MiniNetManPort() int {
	u, e := url.Parse(c.MiniNetMan.URL)
	if e != nil {
		return 0
	}
	if p, e := strconv.Atoi(u.Port()); e == nil {
		return p
	}
	if u.Scheme == "https" {
		return 443
	}
	return 80
}

// PanelPort returns the TCP port of Panel.Listen.
func (c Config) PanelPort() (int, error) {
	_, p, e := net.SplitHostPort(c.Panel.Listen)
	if e != nil {
		return 0, fmt.Errorf("panel.listen: %w", e)
	}
	port, e := strconv.Atoi(p)
	if e != nil || port <= 0 || port > 65535 {
		return 0, fmt.Errorf("panel.listen: invalid port %q", p)
	}
	return port, nil
}
